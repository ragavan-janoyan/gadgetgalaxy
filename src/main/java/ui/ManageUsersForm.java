 private void loadUsersTable() {

        DefaultTableModel model = (DefaultTableModel) tblUsers.getModel();
        model.setRowCount(0);

        for (User u : userService.getAllUsers()) {

            model.addRow(new Object[]{
                u.getUsername(),
                u.getPassword(),
                u.getRole()
            });
        }
    }

