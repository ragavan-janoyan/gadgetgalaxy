    private void btnAddnewsalesuserActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddnewsalesuserActionPerformed
        String username = txtUsername.getText();
        String password = txtPassword.getText();
        String role = cmbRole.getSelectedItem().toString();

        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill all fields!");
            return;
        }

        User newUser = new User(username, password, role);

        boolean added = userService.addUser(newUser);

        if (added) {

            JOptionPane.showMessageDialog(this, "User created successfully!");

            txtUsername.setText("");
            txtPassword.setText("");

            loadUsersTable();

        } else {

            JOptionPane.showMessageDialog(this, "Username already exists!");
        }

    }//GEN-LAST:event_btnAddnewsalesuserActionPerformed

